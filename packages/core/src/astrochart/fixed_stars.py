STAR_KEYS = tuple(s[0] for s in STARS)

_cache: dict = {}


def _stars():
    if "s" not in _cache:
        import numpy as np
        from skyfield.api import Star
        ts, _ = ephemeris._load()
        _cache["s"] = Star(ra_hours=np.array([s[2] / 15 for s in STARS]), dec_degrees=np.array([s[3] for s in STARS]),
                           ra_mas_per_year=np.array([s[4] for s in STARS]), dec_mas_per_year=np.array([s[5] for s in STARS]),
                           epoch=ts.J(1991.25))
    return _cache["s"]


def star_longitudes(utc: datetime) -> dict[str, float]:
    """某时刻全部恒星的视黄经（度，真黄道 + 当日春分点）。一次向量化算完。"""
    from skyfield.framelib import ecliptic_frame
    _, eph = ephemeris._load()
    _, lon, _ = eph["earth"].at(ephemeris._t(utc)).observe(_stars()).apparent().frame_latlon(ecliptic_frame)
    return {k: float(x) % 360.0 for k, x in zip(STAR_KEYS, lon.degrees)}
